// Generates ui/locales.js from the native app's string table so both apps share one set of PL/EN strings.
// Usage: node scripts/gen-locales.mjs
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../../macos/LibreWalletShared/L10n.swift", import.meta.url), "utf8");
const unescape = (s) => s.replace(/\\(["\\nt])/g, (_, c) => ({ n: "\n", t: "\t" })[c] ?? c).replace(/\\u\{([0-9a-f]+)\}/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)));
const out = {};
let lang = null;
for (const line of src.split("\n")) {
  const head = /^\s*\.(pl|en): \[\s*$/.exec(line);
  if (head) { lang = head[1]; out[lang] = {}; continue; }
  if (lang && /^\s*\],?\s*$/.test(line)) { lang = null; continue; }
  const kv = lang && /^\s*"([^"]+)":\s*"((?:[^"\\]|\\.)*)",?\s*$/.exec(line);
  if (kv) out[lang][kv[1]] = unescape(kv[2]);
}
if (!out.pl || !out.en) throw new Error("Could not find .pl/.en tables in L10n.swift");
const body = `// Generated by scripts/gen-locales.mjs from macos/LibreWalletShared/L10n.swift — do not edit.\nexport const locales = ${JSON.stringify(out, null, 1)};\n`;
writeFileSync(new URL("../ui/locales.js", import.meta.url), body);
console.log(`pl: ${Object.keys(out.pl).length} keys, en: ${Object.keys(out.en).length} keys`);
